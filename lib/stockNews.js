export function randomHeadline(sector, direction) {
  const bank = HEADLINE_BANK[sector] || HEADLINE_BANK.default;
  const list = bank[direction] || HEADLINE_BANK.default[direction];
  return list[Math.floor(Math.random() * list.length)];
}
